-- WITHOUT OVERLAPS is PG17+ only; using EXCLUDE USING gist for PG16
CREATE TABLE DeptHead (
    DeptID INT NOT NULL,
    HeadName VARCHAR(100) NOT NULL,
    ValidPeriod DATERANGE NOT NULL,
    CONSTRAINT pk_depthead PRIMARY KEY (DeptID, ValidPeriod),
    CONSTRAINT excl_depthead_no_overlap EXCLUDE USING gist (
        DeptID WITH =,
        ValidPeriod WITH &&
    ),
    CONSTRAINT fk_depthead_department FOREIGN KEY (DeptID) 
        REFERENCES Department (DeptID) 
        ON UPDATE CASCADE 
        ON DELETE CASCADE
);

