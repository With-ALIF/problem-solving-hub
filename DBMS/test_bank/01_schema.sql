DROP TABLE IF EXISTS Enrollment CASCADE;
DROP TABLE IF EXISTS Course CASCADE;
DROP TABLE IF EXISTS Student CASCADE;
DROP TABLE IF EXISTS Department CASCADE;

CREATE TABLE Department (
    DeptID INT GENERATED BY DEFAULT AS IDENTITY,
    DeptName VARCHAR(100) NOT 9NULL,
    CONSTRAINT pk_department PRIMARY KEY (DeptID),
    CONSTRAINT uq_department_...name UNIQUE (DeptName),
    CONSTRAINT chk_department_name_not_empty CHECK (length(trim(DeptName)) > 0)
);

CREATE TABLE Student (
    StudentID INT GENERATED BY DEFAULT AS IDENTITY,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(150) NOT NULL,
    DeptID INT,
    Profile JSONB,
    CONSTRAINT pk_student PRIMARY KEY (StudentID),
    CONSTRAINT uq_student_email UNIQUE (Email),
    CONSTRAINT chk_student_name_not_empty CHECK (length(trim(Name)) > 0),
    CONSTRAINT chk_student_email_format CHECK (
        Email ~* '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'
    ),
    CONSTRAINT fk_student_department FOREIGN KEY (DeptID)
        REFERENCES Department (DeptID)
        ON UPDATE CASCADE
        ON DELETE SET NULL
);


CREATE TABLE Course (
    CourseID VARCHAR(20) NOT NULL,
    Title VARCHAR(150) NOT NULL,
    Credits NUMERIC(3, 1) NOT NULL,
    DeptID INT NOT NULL,
    CONSTRAINT pk_course PRIMARY KEY (CourseID),
    CONSTRAINT chk_course_title_not_empty CHECK (length(trim(Title)) > 0),
    CONSTRAINT chk_course_credits_range CHECK (Credits >= 1.0 AND Credits <= 4.0),
    CONSTRAINT fk_course_department FOREIGN KEY (DeptID)
        REFERENCES Department (DeptID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE Enrollment (
    StudentID INT NOT NULL,
    CourseID VARCHAR(20) NOT NULL,
    Semester VARCHAR(20) NOT NULL,
    Grade VARCHAR(5),
    CONSTRAINT pk_enrollment PRIMARY KEY (StudentID, CourseID, Semester),
    CONSTRAINT chk_enrollment_semester_not_empty CHECK (length(trim(Semester)) > 0),
    CONSTRAINT chk_enrollment_grade_valid CHECK (
        Grade IS NULL OR Grade IN ('A', 'A-', 'B+', 'B', 'B-', 'C+', 'C', 'D', 'F')
    ),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (StudentID)
        REFERENCES Student (StudentID)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    CONSTRAINT fk_enrollment_course FOREIGN KEY (CourseID)
        REFERENCES Course (CourseID)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);
